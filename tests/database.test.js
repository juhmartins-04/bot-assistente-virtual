import test from 'node:test'
import assert from 'node:assert/strict'
import {database,login,OWNER,OTHER,CLIENT,STAFF,PUB} from './helpers/database.js'
let db
await test('schema e migração preservam configuração antiga',async()=>{
 db=await database()
 assert.equal((await db.query('select user_id from public.account_config')).rows[0].user_id,OWNER)
 assert.equal((await db.query('select count(*)::int n from public.app_storage where user_id is null')).rows[0].n,1)
})
await test('contas salvam a mesma chave e ficam isoladas',async()=>{
 await login(db,OWNER)
 await db.query("insert into public.account_config(user_id,key,value) values($1,'config','A') on conflict(user_id,key) do update set value=excluded.value",[OWNER])
 await login(db,OTHER)
 await db.query("insert into public.account_config(user_id,key,value) values($1,'config','B') on conflict(user_id,key) do update set value=excluded.value",[OTHER])
 assert.deepEqual((await db.query('select value from public.account_config')).rows,[{value:'B'}])
 await assert.rejects(db.query("insert into public.clientes(id,user_id,nome_negocio,dados) values('intruso',$1,'Intruso','{}')",[OTHER]))
})
await test('relatório agrega mais de 5000 eventos e respeita datas de Curitiba',async()=>{
 await db.exec('reset role')
 await db.exec(`insert into public.eventos(public_id,tipo,criado_em) select '${PUB}','abertura','2026-10-01 03:00:00+00' from generate_series(1,5001);insert into public.eventos(public_id,tipo,criado_em) values('${PUB}','abertura','2026-10-01 02:59:59+00'),('${PUB}','abertura','2026-11-01 03:00:00+00');`)
 await login(db,OWNER)
 assert.equal((await db.query("select public.relatorio_periodo($1,'2026-10-01','2026-10-31') r",[PUB])).rows[0].r.aberturas,5001)
 await login(db,OTHER)
 assert.equal((await db.query("select public.relatorio_periodo($1,'2026-10-01','2026-10-31') r",[PUB])).rows[0].r.aberturas,0)
})
