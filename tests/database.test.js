await test('backup restaura identificadores, contatos e histórico sem sobrescrever existentes',async()=>{
 await db.exec('reset role')
 await db.query("insert into public.leads(public_id,nome,nota) values($1,'Nome','Nota preservada')",[PUB])
 await login(db,OWNER)
 const backup=(await db.query('select public.backup_operacional() r')).rows[0].r
 assert.equal(backup.eventos.length,5063)
 assert.deepEqual((await db.query('select public.restaurar_backup($1) r',[backup])).rows[0].r,{restaurados:0,preservados:1})
 await db.exec("delete from public.clientes where id='test'")
 assert.equal((await db.query('select count(*)::int n from public.leads')).rows[0].n,0)
 assert.deepEqual((await db.query('select public.restaurar_backup($1) r',[backup])).rows[0].r,{restaurados:1,preservados:0})
 assert.equal((await db.query('select nota from public.leads')).rows[0].nota,'Nota preservada')
 assert.equal((await db.query('select public_id,status from public.clientes')).rows[0].public_id,PUB)
 assert.equal((await db.query('select public_id,status from public.clientes')).rows[0].status,'suspended')
 await assert.rejects(db.query('select public.restaurar_backup($1)',[{versao:2,clientes:[]}]))
})
